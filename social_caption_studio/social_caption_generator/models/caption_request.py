import logging
import os
import time

from odoo import _, api, fields, models
from odoo.exceptions import UserError

from . import caption_engine

_logger = logging.getLogger(__name__)

PARAM_API_KEY = 'social_caption_generator.api_key'
PARAM_MODEL = 'social_caption_generator.model'


class SocialCaptionRequest(models.Model):
    _name = 'social.caption.request'
    _description = 'Social Caption Request'
    _order = 'id desc'

    name = fields.Char(string='Topic / الموضوع', required=True)
    tone = fields.Selection([
        ('friendly', 'Friendly / ودود'),
        ('playful', 'Playful / مرح'),
        ('warm', 'Warm / دافئ'),
        ('elegant', 'Elegant / راقٍ'),
        ('bold', 'Bold / حماسي'),
    ], string='Tone / الأسلوب', required=True, default='friendly')
    language = fields.Selection([
        ('ar', 'Arabic / عربي'),
        ('en', 'English'),
        ('both', 'Both / الاثنين'),
    ], string='Language / اللغة', required=True, default='ar')
    platform = fields.Selection([
        ('instagram', 'Instagram'),
        ('facebook', 'Facebook'),
        ('tiktok', 'TikTok'),
        ('linkedin', 'LinkedIn'),
        ('x', 'X (Twitter)'),
    ], string='Platform / المنصة', required=True, default='instagram')
    business_name = fields.Char(
        string='Business name / اسم النشاط',
        default=lambda self: self.env.company.name)
    business_description = fields.Text(string='About the business / عن النشاط')
    extra_facts = fields.Char(
        string='Facts to include / تفاصيل إضافية',
        help='Price, date, branch, offer… Only these facts are used; nothing is invented.')

    caption_1 = fields.Text(string='1 · Sensory / حسّي', readonly=True)
    caption_2 = fields.Text(string='2 · Moment / لحظة', readonly=True)
    caption_3 = fields.Text(string='3 · Call to action / دعوة', readonly=True)
    engine = fields.Selection([
        ('offline', 'Built-in generator'),
        ('claude', 'Claude'),
    ], string='Generated by', readonly=True)
    generation_note = fields.Char(string='Note', readonly=True)
    generated_on = fields.Datetime(string='Generated on', readonly=True)
    state = fields.Selection([
        ('draft', 'Draft'),
        ('done', 'Generated'),
    ], default='draft', required=True, readonly=True)

    @api.model
    def _claude_settings(self):
        params = self.env['ir.config_parameter'].sudo()
        key = (params.get_param(PARAM_API_KEY) or os.environ.get('ANTHROPIC_API_KEY') or '').strip()
        model = (params.get_param(PARAM_MODEL) or caption_engine.DEFAULT_MODEL).strip()
        return key, model

    def _generate_captions(self):
        self.ensure_one()
        key, model = self._claude_settings()
        if key and not self.env.context.get('social_caption_force_offline'):
            prompt = caption_engine.build_prompt(
                self.name, self.tone, self.language, self.platform,
                self.business_name or '', self.business_description or '', self.extra_facts or '')
            try:
                return caption_engine.generate_with_claude(key, prompt, model), 'claude', ''
            except caption_engine.ClaudeError as exc:
                _logger.warning('Social captions: Claude failed, using built-in generator: %s', exc)
                note = _('%s Used the built-in generator instead.') % exc
        elif key:
            note = ''
        else:
            note = _('Built-in generator. Add an Anthropic API key in Settings for AI-written captions.')
        captions = caption_engine.generate_offline(
            self.name, self.tone, self.language, self.business_name or '',
            seed='%s-%s' % (self.id, time.time_ns()))
        return captions, 'offline', note

    def action_generate(self):
        for record in self:
            if not (record.name or '').strip():
                raise UserError(_('Enter a topic first.'))
            captions, engine, note = record._generate_captions()
            texts = [caption_engine.format_caption(c, record.platform) for c in captions]
            record.write({
                'caption_1': texts[0],
                'caption_2': texts[1],
                'caption_3': texts[2],
                'engine': engine,
                'generation_note': note,
                'generated_on': fields.Datetime.now(),
                'state': 'done',
            })
        return True

    def action_reset(self):
        self.write({
            'caption_1': False, 'caption_2': False, 'caption_3': False,
            'engine': False, 'generation_note': False, 'generated_on': False,
            'state': 'draft',
        })
        return True
