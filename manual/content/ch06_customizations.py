def _build_customization_matrix(mb):
    mb.h2("مصفوفة التخصيصات الشاملة (Customization Matrix)")
    mb.para(
        "يلخّص الجدول التالي كل الوحدات المخصصة الموثقة في هذا الفصل في "
        "مصفوفة واحدة لسهولة الرجوع إليها من قبل فرق التدقيق والتطوير "
        "المستقبلي."
    )
    rows = []
    for group_title, module_keys in GROUPS:
        for key in module_keys:
            if key not in MODULES:
                continue
            man = MODULES[key]["manifest"]
            rows.append([
                key, man.get("name", "—"), group_title, man.get("version", "—"),
                str(len(MODULES[key].get("models", []))),
                str(len(MODULES[key].get("reports", []))),
            ])
    mb.table(
        ["الاسم التقني", "الاسم بالعربية", "المجموعة", "الإصدار", "عدد النماذج", "عدد التقارير"],
        rows,
        caption="مصفوفة التخصيصات الشاملة لكل الوحدات",
        col_widths=[3.5, 4, 3.5, 1.5, 1.5, 1.5],
    )
