def _model_section(mb, model, module_key):
    name = model.get("_name") or (model.get("_inherit")[0] if isinstance(model.get("_inherit"), list) and model.get("_inherit") else model.get("_inherit")) or model["class_name"]
    mb.h4(f"النموذج: {name}")
    if model.get("_description"):
        mb.para(f"الوصف: {model['_description']}")
    if model.get("_inherit"):
        inh = model["_inherit"]
        inh_txt = ", ".join(inh) if isinstance(inh, list) else str(inh)
        mb.para(f"يرث من / يمتد: {inh_txt}")
    fields = model.get("fields", [])
    if fields:
        rows = []
        for f in fields:
            selection = f.get("selection")
            sel_txt = ""
            if selection:
                try:
                    sel_txt = " / ".join(f"{v}={lbl}" for v, lbl in selection)
                except Exception:
                    sel_txt = str(selection)
            rows.append({
                "name": f["name"],
                "arabic": f.get("string") or "—",
                "desc": sel_txt if sel_txt else (f.get("comodel") or "—"),
                "mandatory": f.get("required"),
                "default": "—",
                "validation": "إلزامي" if f.get("required") else "اختياري",
                "example": "—",
                "related": f.get("comodel") or "—",
            })
        mb.field_table(rows, caption=f"حقول النموذج {name} ({module_key})")
    else:
        mb.para("لا توجد حقول مخصصة مستخرجة مباشرة لهذا النموذج (قد يكون امتدادًا سلوكيًا بحتًا لنموذج قياسي دون إضافة حقول).")


