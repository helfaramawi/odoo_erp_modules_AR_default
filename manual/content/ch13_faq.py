def _state_faq(models):
    for model in models:
        for f in model.get("fields", []):
            if f["name"] in ("state", "status") and f.get("selection"):
                labels = [lbl for _, lbl in f["selection"]]
                return " ← ".join(labels)
    return None


def build(mb):
    mb.h1("الأسئلة الشائعة (Frequently Asked Questions)")
    mb.para(
        "يجمع هذا الفصل أكثر من 300 سؤال وجواب: مجموعة أولى عامة حول "
        "استخدام النظام والمفاهيم الأساسية، ومجموعة ثانية مولَّدة مباشرة من "
        "بيانات كل وحدة مخصصة موثقة في الفصل 6 (47 وحدة × 7 أسئلة لكل وحدة) "
        "لضمان تغطية شاملة وحقيقية دون حشو."
    )

    mb.h2("أسئلة عامة حول النظام والاستخدام")
    count = 0
    for q, a in GENERAL_FAQS:
        count += 1
        p = mb.para(f"{count}. س: {q}")
        mb.para(f"     ج: {a}", size=11, color=(0x33, 0x33, 0x33))

    mb.h2("أسئلة تفصيلية حول كل وحدة مخصصة (مولَّدة من الفصل 6)")
    mb.para(
        "لكل وحدة من الوحدات الـ47 الموثقة في الفصل 6، سبعة أسئلة نمطية "
        "إجاباتها مستخرجة مباشرة من نفس البيانات والسرد المستخدم هناك، لضمان "
        "الاتساق الكامل بين الفصلين."
    )
    for group_title, module_keys in ch6.GROUPS:
        mb.h3(group_title)
        for key in module_keys:
            if key not in ch6.MODULES:
                continue
            data = ch6.MODULES[key]
            man = data["manifest"]
            narrative = ch6.NARRATIVE.get(key, ch6.DEFAULT_NARRATIVE)
            name_ar = man.get("name", key)

            qa = []
            qa.append((f"ما هو الغرض من وحدة {name_ar} ({key})؟", narrative["purpose"]))
            qa.append((f"ما المشكلة التي تحلها وحدة {key} مقارنة بسلوك أودو القياسي؟", narrative["problem"]))

            states_desc = _state_faq(data.get("models", []))
            if states_desc:
                qa.append((f"ما هي حالات سير العمل الرئيسية في وحدة {key}؟", f"تمر بالحالات التالية: {states_desc}."))
            else:
                qa.append((f"هل توجد حالات سير عمل صريحة (state) في وحدة {key}؟", "لا يوجد حقل حالة صريح مستخرج لهذه الوحدة؛ راجع الفصل 6 لتفاصيل بنيتها الفعلية."))

            n_reports = len(data.get("reports", []))
            qa.append((f"كم عدد التقارير المتاحة في وحدة {key}؟",
                       f"تتوفر {n_reports} تقارير مختلفة لهذه الوحدة؛ راجع الفصل 8 للقائمة الكاملة." if n_reports
                       else "لا توجد تقارير QWeb مخصصة لهذه الوحدة."))

            depends = man.get("depends", [])
            qa.append((f"على أي وحدات تعتمد {key}؟",
                       ("تعتمد على: " + "، ".join(depends) + ".") if depends else "لا توجد اعتماديات صريحة بخلاف وحدات أودو الأساسية."))

            qa.append((f"ما أهم تحسين مستقبلي مقترح لوحدة {key}؟", narrative["future"]))
            qa.append((f"ما أبرز قيد معروف حاليًا في وحدة {key}؟", narrative["limitations"]))

            for q, a in qa:
                count += 1
                mb.para(f"{count}. س: {q}")
                mb.para(f"     ج: {a}", size=11, color=(0x33, 0x33, 0x33))

    mb.note(f"إجمالي عدد الأسئلة والأجوبة في هذا الفصل: {count}.")
