    mb.bullets([
        "عدد اللجان المشكَّلة (تشكيل/فحص/بت) حسب النوع",
        "توزيع مناقصات البت الفني والمالي حسب الحالة (مسودة/فتح فني/فتح مالي/مُرسى/أمر شراء منشأ/ملغاة)",
        "عدد أذونات الإضافة (نموذج 1) المعلّقة والمعتمدة",
    ])

    mb.h2("لوحة المخازن والجرد (Warehouse & Inventory Dashboard)")
    mb.para("تعرض حالة الجرد الحكومي الأخير ونسبة العجز إلى إجمالي الأصناف المجرودة، وحالة العُهد المسجَّلة.")
    mb.bullets([
        "نسبة العجز (Deficit) إلى إجمالي بنود آخر جلسة جرد",
        "عدد سجلات العُهد النشطة حسب الموظف/الإدارة",
    ])

    mb.h2("لوحة المزايدات (Auction Dashboard)")
    mb.bullets([
        "عدد عقود الإيجار النشطة وإجمالي قيمتها التعاقدية",
        "إجمالي المُحصَّل والمتبقي من عقود الإيجار",
        "إجمالي إيرادات المزايدات",
    ])

    mb.h2("الاتجاه الشهري والتنبيهات (Monthly Trend & Alerts)")
    mb.para("تعرض اللوحة رسمًا بيانيًا لاتجاه المدفوعات الشهرية على مدار السنة المالية، إلى جانب قسم تنبيهات يجمّع أي مؤشر يتجاوز عتبة محددة مسبقًا (مثال: نسبة عجز جرد مرتفعة، أو ارتباطات مقتربة من استنفاد بند الموازنة).")
