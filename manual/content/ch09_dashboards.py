        "الدالة تُنادي self._collect_data() وتُعيد نتيجتها مباشرة، بينما تلي "
        "ذلك كتلة برمجية طويلة تشير لمتغيرات غير معرَّفة (env، sc، pyo) لا "
        "يمكن الوصول إليها أبدًا في التنفيذ الفعلي. يجب على فريق الصيانة "
        "مراجعة هذا الملف لإزالة الشيفرة الميتة أو دمج منطقها الفعلي إن كان "
        "مقصودًا ضمن _collect_data."
