        "من الخادم، وليس كلوحة قيادة قياسية مبنية بإطار عمل أودو للعميل "
        "(OWL Client Action). تُقسَّم اللوحة الواحدة فعليًا إلى عدة أقسام "
        "وظيفية تقابل تصنيفات لوحات القيادة المطلوبة في هذا الدليل."
