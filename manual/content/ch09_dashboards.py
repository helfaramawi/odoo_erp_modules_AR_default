        "إجمالي مبالغ المدفوعات المرحّلة والمؤرشفة",
        "إجمالي عدد الارتباطات وتوزيعها حسب الحالة",
        "إجمالي مبلغ الارتباطات النشطة (معتمد/مجنَّب/مُسمَّح) والرصيد المتاح المتبقي",
        "قائمة أعلى 10 عمليات صرف قيمة (المسلسل، المصلحة، المبلغ، الحالة)",
