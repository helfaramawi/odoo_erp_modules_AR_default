    mb.para("تُغطى الاحتياجات التشغيلية اليومية لمديري المصالح عبر نفس لوحة القيادة التنفيذية الموحّدة أعلاه، دون وجود لوحة تشغيلية منفصلة مبسّطة حاليًا.")
    mb.note("[عنصر نائب] يمكن مستقبلاً استحداث نسخة مبسّطة من اللوحة موجَّهة لمديري المصالح تعرض فقط المؤشرات ذات الصلة بإدارتهم.")

