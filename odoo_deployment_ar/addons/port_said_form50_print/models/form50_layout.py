def get_css_position(field_id):
    """إرجاع (left_pct, top_pct) كقيم CSS مئوية جاهزة للاستخدام."""
    entry = FIELD_POSITIONS.get(field_id)
    if entry is None:
        return None
    return entry[0], entry[1]


def get_all_positions():
    """إرجاع dict بسيط {id: (left_pct, top_pct)} متوافق مع _form50_positions."""
    return {fid: (v[0], v[1]) for fid, v in FIELD_POSITIONS.items()}
